/* Mint a deterministic Identity for negative-case wire signing. Keyed on
 * the participant id so all five protocols' negative cases get
 * byte-identical signers for the same `from` field. */
static int _make_signer_identity(const char *pid, identity_t **out) {
    /* SHA-256 of "at-conformance:neg:<pid>" gives 32 raw bytes; we use the
     * first 16 as the UUID (with the v4-shaped bits set). */
    char namestr[128];
    snprintf(namestr, sizeof(namestr), "at-conformance:neg:%s", pid);
    unsigned char sha[32];
    crypto_hash_sha256(sha, (const unsigned char *)namestr, strlen(namestr));
    uuid_t uuid;
    memcpy(uuid, sha, 16);
    uuid[6] = (uuid[6] & 0x0F) | 0x40;
    uuid[8] = (uuid[8] & 0x3F) | 0x80;

    char addr[ADDR_LEN + 1] = "10.0.90.1";
    char nickname[NAME_LEN + 1] = {0};
    snprintf(nickname, sizeof(nickname), "%s.neg", pid);

    if (identity_create(&uuid, addr, nickname, pid, out) != 0 || *out == NULL) {
        return -1;
    }

    /* Overwrite the randomly-generated keypairs with deterministic ones,
     * keyed on the participant id with role-suffixed labels. */
    char label[64];
    unsigned char digest[32];
    unsigned char hex_seed[crypto_sign_SEEDBYTES * 2 + 1];

    snprintf(label, sizeof(label), "at-conformance:neg:sig:%s", pid);
    crypto_hash_sha256(digest, (const unsigned char *)label, strlen(label));
    hexlify(digest, crypto_sign_SEEDBYTES, hex_seed);
    hex_seed[crypto_sign_SEEDBYTES * 2] = '\0';
    if (signature_init(&(*out)->signature, hex_seed,
                       crypto_sign_SEEDBYTES * 2) != 0)
        return -1;

    snprintf(label, sizeof(label), "at-conformance:neg:enc:%s", pid);
    crypto_hash_sha256(digest, (const unsigned char *)label, strlen(label));
    hexlify(digest, crypto_box_SEEDBYTES, hex_seed);
    hex_seed[crypto_box_SEEDBYTES * 2] = '\0';
    if (encryptor_init(&(*out)->encryptor, hex_seed,
                       crypto_box_SEEDBYTES * 2) != 0)
        return -1;
    return 0;
}

/* Look up `from` and `function` for the given step_id in a base scenario
 * JSON mirror. Returns 0 on success; -1 if not a source step or not found. */
static int _find_step(json_t *base_root, int step_id,
                      const char **out_from, const char **out_function) {
    json_t *data = json_object_get(base_root, "data");
    json_t *steps = json_object_get(data, "steps");
    if (!json_is_array(steps)) return -1;
    size_t n = json_array_size(steps);
    for (size_t i = 0; i < n; i++) {
        json_t *s = json_array_get(steps, i);
        json_t *id_node = json_object_get(s, "id");
        if (!json_is_integer(id_node)) continue;
        if ((int)json_integer_value(id_node) != step_id) continue;
        if (json_object_get(s, "in_response_to") != NULL) return -2;
        *out_from = json_string_value(json_object_get(s, "from"));
        *out_function = json_string_value(json_object_get(s, "function"));
        if (*out_from == NULL || *out_function == NULL) return -1;
        return 0;
    }
    return -1;
}

int at_neg_run_wire(const at_case_t *c, at_case_result_t *out_result) {
    char err[256] = {0};
    struct timespec t0, t1;
    clock_gettime(CLOCK_MONOTONIC, &t0);

    const char *based_on = json_string_value(json_object_get(c->data, "based_on"));
    json_t *mutation = json_object_get(c->data, "mutation");
    json_t *expected = json_object_get(c->data, "expected");
    const char *expected_reason = json_string_value(
        json_object_get(expected, "reason_class"));
    if (based_on == NULL || mutation == NULL || expected_reason == NULL) {
        snprintf(err, sizeof(err), "negative case missing based_on/mutation/expected");
        at_case_result_set_fail(out_result, 0, "AssertionError", err);
        return 0;
    }

    const char *json_root = at_runner_corpus_json_root();
    char *base_path = NULL;
    if (at_neg_resolve_based_on(json_root, based_on, &base_path) != 0) {
        snprintf(err, sizeof(err), "could not resolve based_on path %s", based_on);
        at_case_result_set_fail(out_result, 0, "AssertionError", err);
        return 0;
    }
    json_t *base_root = NULL;
    int lc = at_neg_load_base_case(base_path, &base_root);
    free(base_path);
    if (lc != 0) {
        snprintf(err, sizeof(err), "could not load base case from %s", based_on);
        at_case_result_set_fail(out_result, 0, "AssertionError", err);
        return 0;
    }

    json_t *step_node = json_object_get(mutation, "step_id");
    int step_id = json_is_integer(step_node) ? (int)json_integer_value(step_node) : 1;
    const char *from_id = NULL, *function = NULL;
    int find_rc = _find_step(base_root, step_id, &from_id, &function);
    if (find_rc != 0) {
        snprintf(err, sizeof(err),
                 "negative: step_id %d not a source step in %s", step_id, based_on);
        json_decref(base_root);
        at_case_result_set_fail(out_result, 0, "AssertionError", err);
        return 0;
    }

    identity_t *sender = NULL;
    if (_make_signer_identity(from_id, &sender) != 0 || sender == NULL) {
        snprintf(err, sizeof(err), "could not build signer for %s", from_id);
        json_decref(base_root);
        at_case_result_set_fail(out_result, 0, "AssertionError", err);
        return 0;
    }
    public_identity_t *sender_pub = NULL;
    if (identity_publish(sender, &sender_pub) != 0 || sender_pub == NULL) {
        snprintf(err, sizeof(err), "identity_publish failed");
        identity_free(sender);
        json_decref(base_root);
        at_case_result_set_fail(out_result, 0, "AssertionError", err);
        return 0;
    }

    /* Build a generic signed Message: process = the case's protocol
     * (same as base_case.protocol), function from the step, data = "{}". */
    net_wire_msg_t msg = {0};
    strncpy(msg.process, c->protocol, PROC_NAME_LEN);
    msg.process[PROC_NAME_LEN] = '\0';
    msg.function = strdup(function);
    const char *empty = "{}";
    msg.data_len = strlen(empty);
    msg.data = malloc(msg.data_len);
    memcpy(msg.data, empty, msg.data_len);
    msg.to_whom.type = RECIPIENT_BROADCAST;
    memcpy(&msg.from_whom, sender_pub, sizeof(public_identity_t));
    msg.encrypt = false;

    uint8_t *clean = NULL;
    size_t clean_len = 0;
    if (net_message_to_wire(&msg, sender, &clean, &clean_len) != 0) {
        snprintf(err, sizeof(err), "net_message_to_wire failed");
        free(msg.function); free(msg.data);
        smrt_deref(sender_pub); identity_free(sender);
        json_decref(base_root);
        at_case_result_set_fail(out_result, 0, "AssertionError", err);
        return 0;
    }
    free(msg.function);
    free(msg.data);

    uint8_t *mutated = NULL;
    size_t mutated_len = 0;
    int mrc = at_neg_apply_mutation(clean, clean_len, mutation, &mutated, &mutated_len);
    free(clean);
    if (mrc == -2) {
        /* Mutation op not supported by this build; skip the case. */
        smrt_deref(sender_pub); identity_free(sender);
        json_decref(base_root);
        at_case_result_set_skip(out_result, "mutation op not supported in v1");
        return 0;
    }
    if (mrc != 0) {
        snprintf(err, sizeof(err), "mutation application failed (rc=%d)", mrc);
        smrt_deref(sender_pub); identity_free(sender);
        json_decref(base_root);
        at_case_result_set_fail(out_result, 0, "AssertionError", err);
        return 0;
    }

    /* Categorize parser verdict. */
    const char *observed = NULL;
    net_wire_msg_t parsed = {0};
    int prc = net_message_from_wire(mutated, mutated_len, sender_pub, &parsed);
    if (prc != 0) {
        observed = at_neg_classify_op(mutation);
    } else if (!parsed.verified) {
        observed = "signature_verification_failed";
    } else {
        observed = "no_rejection_observed";
    }
    net_wire_msg_free(&parsed);
    free(mutated);
    smrt_deref(sender_pub);
    identity_free(sender);
    json_decref(base_root);

    clock_gettime(CLOCK_MONOTONIC, &t1);
    int duration_ms = (int)((t1.tv_sec - t0.tv_sec) * 1000
                            + (t1.tv_nsec - t0.tv_nsec) / 1000000);
    if (strcmp(observed, expected_reason) == 0) {
        at_case_result_set_pass(out_result, duration_ms);
    } else {
        snprintf(err, sizeof(err),
                 "reason_class mismatch: expected %s, observed %s",
                 expected_reason, observed);
        at_case_result_set_fail(out_result, duration_ms, "AssertionError", err);
    }
    return 0;
}
